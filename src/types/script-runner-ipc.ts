/**
 * Narrow check for whether an arbitrary value looks like a `HandleRef`.
 * Useful in dispatcher / proxy code that walks args or return values
 * looking for handle-shaped objects to translate.
 *
 * Intentionally structural — doesn't import the type, so it survives
 * cross-bundle boundaries cleanly.
 */
export function isHandleRef(value: unknown): value is HandleRef {
  return (
    typeof value === 'object' &&
    value !== null &&
    (value as { __handleRef?: unknown }).__handleRef === true &&
    typeof (value as { id?: unknown }).id === 'string' &&
    typeof (value as { kind?: unknown }).kind === 'string'
  );
}
