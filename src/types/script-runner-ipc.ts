// ─── Child → Parent ─────────────────────────────────────────────────────────

/**
 * Child notifying parent that it has begun executing a specific script run.
 * Sent immediately before invoking the user's AsyncFunction body; lets the
 * parent track the active script so a subsequent host-driven SIGKILL (on
 * missed heartbeat) can be surfaced with the offending script name.
 */
export interface ScriptRunningNotice {
  type:       'script-running';
  runId:      string;
  scriptId:   string;
  scriptName: string;
  startedAt:  number;
}

/**
 * Child returning the result of a completed script run. Either a value
 * (typically `undefined` — most user scripts run for side effects) or a
 * serialized error. Mirrors the shape of the existing `executeScript`
 * return value, just delivered over IPC instead of a function return.
 */
export interface RunScriptResult {
  type:        'run-result';
  runId:       string;
  scriptId:    string;
  ok:          boolean;
  value?:      unknown;
  error?:      SerializedError;
  /** Wall-clock execution duration in ms; measured inside the child. */
  durationMs:  number;
}

/**
 * Child invoking a method on the parent's api surface. Either targets the
 * top-level api (`targetHandle === undefined`, `method` is a dotted path
 * like `db.collection` or `chat.getMessages`) or a specific handle's method
 * (`targetHandle` is the HandleRef, `method` is just the method name).
 *
 * Args may contain `HandleRef` values when the user passed a handle as an
 * argument (e.g., `await collection.find()` where `collection` is a handle).
 *
 * `hasSignal` is `true` when the original call passed `opts.signal` —
 * the child stores the AbortSignal locally and emits `AbortRequest` if the
 * signal aborts before the response arrives.
 */
export interface ApiProxyRequest {
  type:          'api-request';
  requestId:     string;
  /** Run scope — used by the dispatcher for permission checks and transient-handle scoping. */
  runId:         string;
  scriptId:      string;
  /** Either a dotted-path on the top-level api, or a method name when `targetHandle` is set. */
  method:        string;
  args:          unknown[];
  /** Present when invoking a method on a previously-returned object handle. */
  targetHandle?: HandleRef;
  /** True if `opts.signal` was supplied; child may emit AbortRequest later. */
  hasSignal?:    boolean;
  /**
   * v0.26.1 — diagnostic-only. Records which of the proxy's three-tier
   * runId-resolution fallbacks produced `runId` at dispatch time:
   *
   *   - `'context'`  — `runIdContext.getStore()` (AsyncLocalStorage). Dispatch
   *     was issued inside a handler-fire (`runIdContext.run(handler-…, …)`)
   *     OR inside the script body wrapped by AsyncLocalStorage propagation.
   *   - `'latest'`   — `latestRunIdByScript.get(scriptId)`. Dispatch was
   *     issued OUTSIDE any runIdContext.run, falling through to the per-
   *     script latest-run map. Typical for cross-run handle method calls
   *     and detached IIFEs from broadcast handlers.
   *   - `'ctx'`      — the originating proxy's `ctx.runId`. Reached only
   *     when no runIdContext is active AND latestRunIdByScript hasn't
   *     been populated (essentially defensive — should be very rare).
   *
   * Surfaced in the parent's `RunCompletedError` message when a late
   * dispatch arrives, so post-mortem analysis can pin the leak class
   * without re-instrumenting the proxy. Optional — older parents that
   * don't read this field are forward-compatible (the parent treats
   * `undefined` as "unknown source").
   */
  _runIdSource?: 'context' | 'latest' | 'ctx';
}

/**
 * Child requesting the parent to abort an in-flight `ApiProxyRequest`.
 * Triggered by the user-script's `AbortController.abort()` firing on a
 * signal that was passed to a proxy method.
 *
 * Parent's dispatcher calls `controller.abort()` on the real api call;
 * the api rejects with `AbortError` per its existing semantics; parent
 * sends back an `ApiProxyResponse { ok: false, error }`.
 *
 * Idempotent: repeated aborts for the same `requestId` are no-ops.
 */
export interface AbortRequest {
  type:      'abort-request';
  requestId: string;
}

/**
 * Child requesting a streaming api call (v1.0.0-rc.9 — currently only
 * `'llm.generateStream'`). Wire-shape mirrors `ApiProxyRequest` but the
 * parent answers with zero-or-more `StreamChunkMessage` followed by a
 * single terminal `StreamEndMessage`, rather than a single `ApiProxyResponse`.
 *
 * `hasSignal` reuses the existing `AbortController`/`AbortRequest` plumbing
 * — the parent injects a signal into the request options and the child's
 * `AbortSignal` is wired to emit `AbortRequest` on abort.
 *
 * Cancellation paths beyond AbortSignal:
 *   - Consumer breaks out of the `for await` loop → child sends
 *     `StreamCancelRequest`. Parent calls `.return()` on the upstream
 *     iterator, propagating teardown to the underlying HTTP request.
 *   - Run ends / script torn down → parent sweeps any open streams owned
 *     by the affected run + sends final `StreamEndMessage { ok: false }`.
 */
export interface StreamRequest {
  type:          'stream-request';
  requestId:     string;
  runId:         string;
  scriptId:      string;
  /** Currently only `'llm.generateStream'`. Forward-extensible if other streaming methods are added later. */
  method:        string;
  args:          unknown[];
  /** True if `opts.signal` was supplied; child may emit `AbortRequest` later. Same semantics as `ApiProxyRequest.hasSignal`. */
  hasSignal?:    boolean;
  /** v0.26.1 — diagnostic-only. Same three-tier resolution as `ApiProxyRequest._runIdSource`. See that field's JSDoc. */
  _runIdSource?: 'context' | 'latest' | 'ctx';
}

/**
 * Parent forwarding one chunk from the upstream `spindle.generate.rawStream`
 * iterator. The `chunk` payload is structurally a `StreamChunk` from
 * `src/types/script.ts` — the boundary leaves it as `unknown` so this IPC
 * type doesn't take a dependency on the user-facing surface.
 */
export interface StreamChunkMessage {
  type:      'stream-chunk';
  requestId: string;
  chunk:     unknown;
}

/**
 * Parent signalling the end of a stream. Exactly one of these per
 * `StreamRequest`, after zero-or-more `StreamChunkMessage`s.
 *
 *   - `ok: true`  — upstream iterator completed normally. No `error`.
 *   - `ok: false` — upstream rejected, consumer aborted, or run ended
 *     mid-stream. `error` carries the serialized failure.
 */
export interface StreamEndMessage {
  type:      'stream-end';
  requestId: string;
  ok:        boolean;
  /** Present when `ok === false`. */
  error?:    SerializedError;
}

/**
 * Child telling the parent that the consumer's `for await` loop ended
 * before the stream did — typically a `break`, a `throw` propagating out
 * of the loop body, or the loop's caller throwing. Parent calls `.return()`
 * on the upstream iterator to tear down the in-flight HTTP request.
 *
 * Distinct from `AbortRequest`, which represents an external `AbortSignal`
 * firing. Both end the stream; cancel is the cooperative path, abort the
 * imperative one. Idempotent — repeated cancels for the same requestId
 * are no-ops.
 */
export interface StreamCancelRequest {
  type:      'stream-cancel';
  requestId: string;
}

