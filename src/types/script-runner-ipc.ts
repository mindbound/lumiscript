/**
 * Phase 9d.3 — parent firing a registered handler. The child looks up
 * the handler by `(scriptId, handlerId)`, runs it inside an
 * AsyncLocalStorage context that overrides the proxy's `runId` for any
 * api.* calls the handler makes, sends back `HandlerResult`.
 *
 * Handler args are JSON-cloneable per-kind contexts (`MacroContext`,
 * `MacroInterceptorCtx`, etc.). For tool handlers, `api` is NOT in the
 * args — it gets injected by the child runtime from the per-script proxy.
 */
export interface RunHandlerRequest {
  type:        'run-handler';
  /**
   * Fresh per-fire `runId`. The parent registers a minimal `activeRun`
   * entry under this id for the duration of the handler call so the
   * child's `dispatch` (now AsyncLocalStorage-keyed for `runId`) routes
   * back to the right api.
   */
  runId:       string;
  scriptId:    string;
  handlerId:   string;
  kind:        HandlerKind;
  /** Per-kind handler arguments. JSON-cloneable. */
  args:        unknown[];
  /** Async-loop timeout for this handler invocation (mirrors RunScriptRequest.timeoutMs). */
  timeoutMs:   number;
  /**
   * Live activeContext snapshot taken at handler-fire time (parent-side, from
   * `binding.ts`). Used by the child to override sync getters
   * (`api.chat.getChatId()`, future symmetric `characterId` getters) for
   * the duration of this handler invocation via a per-fire AsyncLocalStorage
   * scope (`liveContextStore.run(...)` in `child-entry.ts`).
   *
   * Why this exists: without these fields, the child's sync getters fall
   * back to `ctx.chatIdAtStart` / `ctx.characterIdAtStart` — values
   * snapshotted at SCRIPT-LOAD time and never refreshed. Long-lived
   * handlers (widget click, modal `onDismiss`, drawer-tab `onActivate`,
   * input-bar `onClick`, tool fires, etc.) that run after the user has
   * switched chats would otherwise see stale `null`s. Closes the residual
   * the v0.23.2 stale-active-context fix left on the sync-API path.
   */
  chatIdAtFire:      string | null;
  characterIdAtFire: string | null;
}

/**
 * Phase 9d.3 — child returning the result of a handler fire. Mirrors
 * `RunScriptResult`'s envelope but routed to the wrapper closure that
 * lives in the parent's per-handler `pendingHandlerCalls` map.
 */
export interface HandlerResult {
  type:       'handler-result';
  runId:      string;
  ok:         boolean;
  value?:     unknown;
  error?:     SerializedError;
  durationMs: number;
}

/**
 * Phase 9d.3 — parent telling the child to drop ALL handler closures and
 * the proxy belonging to a script. Sent on script-unregister (extension
 * disable, script delete, etc.). Mirrors `BroadcastClearMessage` in
 * scope but covers the function-handler registry too.
 */
export interface ScriptUnregisterMessage {
  type:     'script-unregister';
  scriptId: string;
}

/**
 * Phase 9d.4.e-2-b — parent notifying the child that a float widget's
 * frontend-cached position has changed via a user drag. Fires once per
 * `ls_float_widget_drag_end` echo from the FE, BEFORE any user-registered
 * `onDragEnd` handlers are dispatched (handlers ride the standard
 * register-handler IPC path). This ordering guarantees that a user's
 * `onDragEnd` callback observing `handle.getPosition()` sees the new
 * position synchronously inside the callback.
 *
 * Independent of registration: even when zero `onDragEnd` handlers are
 * registered, the notice keeps `getPosition()` accurate after a drag.
 *
 * Programmatic position changes (`handle.moveTo`) update the proxy's
 * `positionCache` synchronously and don't go through this path — the
 * notice exists specifically to bridge FE-driven position changes back
 * into child-side state.
 */
export interface FloatWidgetPositionNotice {
  type:     'float-widget-position';
  widgetId: string;
  x:        number;
  y:        number;
}

/**
 * Phase 9d.4.d — parent notifying the child that a previously-opened
 * advanced modal has been dismissed (user click, script call, or teardown).
 *
 * Bus-like fire-and-forget pattern: the parent registers ONE internal
 * `onDismiss` listener with the canonical handle when `showAdvancedModal`
 * fires, and on dismissal sends this notice to the child. The child's
 * api-proxy module-scope `advancedModalState` table looks up the modalId,
 * flips its cached `dismissed` flag, and invokes all locally-stored user
 * listeners (the closures registered via `handle.onDismiss(fn)`).
 *
 * This avoids the alternative of one `register-handler` IPC per
 * `onDismiss(fn)` call — a script that registers ten handlers on the same
 * modal pays for ten parent-side wrapper closures + the matching
 * `unregister-handler` storms when they're dropped. The bus pattern is one
 * IPC per modal lifecycle, regardless of listener count.
 */
export interface AdvancedModalDismissedNotice {
  type:    'advanced-modal-dismissed';
  modalId: string;
  reason:  AdvancedModalDismissReason;
}

/**
 * Parent asking the child to report its own process resource usage. Used by
 * the v0.28.0+ diagnostics panel to surface script-runner subprocess health
 * (RSS, heap, CPU time) without adding host-side periodic instrumentation.
 *
 * Child responds with `DiagnosticStatsResponse` carrying the same requestId.
 * Parent times the request out via the diagnostic-collector's caller — no
 * timeout enforcement on this end; if the child is hung the response simply
 * never arrives and the collector falls back to "not available".
 */
export interface DiagnosticStatsRequest {
  type:      'diagnostic-stats-request';
  requestId: string;
}

/**
 * v1.0.0-rc.6 — per-script state snapshot the parent sends to a child worker
 * when a script first dispatches to that worker (cold spawn OR post-respawn
 * OR post-rebalance reassignment). Lets the child pre-populate proxy-side
 * stable-id caches that would otherwise diverge from the parent's view.
 *
 * Empty fields MUST be omitted (not sent as `{}`); consumers treat an
 * absent field as "no state to seed for that surface". The child tolerates
 * unknown top-level keys for forward-compat — newer parents can extend the
 * snapshot without breaking older child builds.
 *
 * ─── Why this exists ───────────────────────────────────────────────────────
 *
 * Eviction asymmetry: parent-side persistent state (dom-registry, etc.)
 * survives worker death; child-side caches (api-proxy module-scope maps)
 * die with the worker. Without seeding, the proxy's child-side cache
 * regenerates IDs from scratch post-respawn while the parent's view still
 * holds the original ones — same stable identifier maps to two different
 * elementIds across the lifetime asymmetry boundary.
 *
 * The v1.0.0-rc.3 alias-storage hotfix in `handleDomInjectRequest` papers
 * over the divergence by storing handles under BOTH the canonical id and
 * the proxy's regenerated id; this snapshot replaces that hotfix with the
 * architecturally clean approach (child snapshots state from parent on
 * bootstrap, single source of truth). Keeping the hotfix in place as
 * belt-and-suspenders until state-sync burns in for a release or two.
 *
 * ─── Inventory of caches today (rc.6) ─────────────────────────────────────
 *
 * Only `domStableIdToElementId` needs syncing. Other proxy-side maps
 * (`advancedModalState`, `floatWidgetState`, `latestRunIdByScript`) don't
 * carry cross-respawn stable-id idempotency semantics — modals / widgets
 * are per-creation entities without a user-supplied stableId mapping, and
 * the run-id tracker is runtime routing state that re-establishes on each
 * dispatch.
 */
export interface ScriptStateSnapshot {
  scriptId: string;
  /**
   * `stableId → elementId` for every DOM element this script has injected
   * with a user-supplied stable ID. Omitted when the script has no
   * stable-id-tagged elements (the common case at startup).
   */
  domStableIds?: Record<string, string>;
}

/**
 * Parent → child message carrying a `ScriptStateSnapshot` for a script
 * about to dispatch on this worker. Sent BEFORE the corresponding
 * `RunScriptRequest` (Bun IPC is FIFO per channel, so ordering is
 * guaranteed without an ack handshake).
 *
 * Idempotent on receipt: applying the same snapshot twice is a no-op.
 * Empty snapshots are not sent (parent gates on `hasContent`).
 */
export interface ScriptStateSyncMessage {
  type:     'script-state-sync';
  snapshot: ScriptStateSnapshot;
}

