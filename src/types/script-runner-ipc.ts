/**
 * ============================================================================
 * LUMISCRIPT — SCRIPT-RUNNER IPC TYPES
 * ============================================================================
 * Discriminated union types for messages exchanged between the LumiScript
 * main backend (parent) and the script-runner child subprocess.
 *
 * Convention mirrors `messages.ts`: every message has a `type` field as the
 * discriminant on both sides.
 *
 * Shared between parent and child — drift between the two implementations
 * is caught at typecheck time as long as both sides import from this file.
 *
 * Architecture context: see `notes/step-2-design.md`.
 *
 * ─── Direction notation ─────────────────────────────────────────────────────
 *   Parent → Child:   `ParentToChildMessage` (this file's first union)
 *   Child  → Parent:  `ChildToParentMessage` (second union)
 *
 * Naming convention:
 *   - Request types end with `-request` and expect a corresponding response
 *   - Notice types end with `-notice` and are fire-and-forget
 *   - Lifecycle messages use plain past-tense verbs (`run-result`, etc.)
 *
 * ─── Correlation IDs ────────────────────────────────────────────────────────
 *   `runId`        Unique per script execution. Generated by the parent at
 *                  run-dispatch time. Used to scope transient handles, route
 *                  console output, and identify the active script in error
 *                  reporting.
 *   `requestId`    Unique per api proxy call. Generated by the child at
 *                  call time. Used to correlate ApiProxyRequest with
 *                  ApiProxyResponse and to target AbortRequest.
 *   `subId`        Unique per broadcast subscription. Generated by the
 *                  child at subscribe time.
 */

