// ─── Shared shapes ──────────────────────────────────────────────────────────

/**
 * Opaque identifier for a host-resident object (e.g. a `Collection` returned
 * by `api.db.collection`, a `DOMHandle` returned by `api.ui.dom.injectAtMessage`).
 * The child receives this in place of the real object and uses it in subsequent
 * api calls that target the underlying object.
 */
export type HandleId = string;

/**
 * Wire format for a host-resident object handle. Sent from parent to child
 * as the result of api calls that return objects with methods. The child's
 * proxy generator uses `kind` to pick the correct proxy class to wrap the
 * returned reference.
 *
 * Transient handles (e.g. `Collection`) are dropped on script-run completion.
 * Persistent handles (e.g. `DOMHandle`, `RegisteredMacroHandle`) are tied to
 * the owning script's lifecycle via the existing `clearByScriptId` patterns.
 * The lifecycle classification lives in the dispatcher, not on the wire.
 */
export interface HandleRef {
  __handleRef: true;
  id: HandleId;
  kind: HandleKind;
}

/**
 * Stable identifiers for the categories of host-resident objects that can
 * be exposed to the child as handles. Each kind has a corresponding proxy
 * class on the child that knows how to dispatch method calls.
 */
export type HandleKind =
  | 'Collection'
  | 'DOMHandle'
  | 'CollapsibleDOMHandle'
  | 'ProgressBarHandle'
  | 'RegisteredMacroHandle'
  | 'RegisteredToolHandle'
  | 'RegisteredDrawerTab'
  | 'RegisteredInputBarAction'
  | 'RegisteredCommandHandle'
  | 'RegisteredFloatWidget'
  | 'BroadcastSubscription'
  | 'MacroInterceptorHandle'
  | 'ContentProcessorHandle'
  | 'StyleHandle'
  | 'EnclaveHandle'
  | 'MountedComponent';

/**
 * Serialised form of a thrown error. Errors don't survive structured-clone
 * intact across IPC boundaries, so we capture name/message/stack explicitly.
 */
export interface SerializedError {
  name:    string;
  message: string;
  stack?:  string;
}

// ─── Parent → Child ─────────────────────────────────────────────────────────

/**
 * Parent dispatching a script run to the child. Carries everything the child
 * needs to execute the script body in its sandbox: code, trigger event data,
 * granted permissions, timeout, and identity (script + run + user).
 *
 * The child responds with a `RunResult` once execution completes (success or
 * error). During the run, the child may emit any number of `ApiProxyRequest`,
 * `BroadcastSubscribeMessage`, `BroadcastUnsubscribeMessage`, `AbortRequest`,
 * `ScriptRunningNotice`, and `ConsoleEntryNotice` messages.
 */
export interface RunScriptRequest {
  type:               'run-script';
  runId:              string;
  scriptId:           string;
  scriptName:         string;
  /**
   * The script's declared type — exposed to user code as `script.type`. The
   * dispatcher copies this directly from the real `Script.type` field
   * (no synth-shim hardcoding from Phase 7's prototype).
   */
  scriptType:         ScriptType;
  /** The user-script source to execute. */
  code:               string;
  /** The trigger event payload (e.g. MESSAGE_SENT data) — passed as `data` to the AsyncFunction. */
  data:               unknown;
  /** Async timeout window. The existing Promise.race in executor.ts moves to the child. */
  timeoutMs:          number;
  /** Permissions granted to the LumiScript extension (NOT per-script — see lumiscript_permission_model.md). */
  grantedPermissions: string[];
  /** User ID for operator-scoped api calls. Optional in single-user mode. */
  userId?:            string;
  /** Whether the script has the `allowDangerous` flag (gates http etc.). */
  allowDangerous:     boolean;
  /**
   * #11 — which sandbox engine runs the user body: `'asyncfn'` (the
   * `new AsyncFunction` path, default) or `'quickjs'` (the QuickJS-WASM
   * isolate). Optional for forward-compat with older parents; the child
   * defaults to `'asyncfn'` when unset.
   */
  engineMode?:        'asyncfn' | 'quickjs';
  /**
   * Phase 9d.1 — snapshot of the active chat / character ID at run-dispatch
   * time. Used by the child to implement sync-returning api methods like
   * `api.chat.getChatId()` locally without an IPC roundtrip.
   *
   * For trigger fires this matches the chat that triggered the event;
   * activeContext doesn't change mid-run so the snapshot is correct.
   * Long-lived registered handlers (Phase 9d.3) will need a different
   * pattern — when a registered macro's handler fires from a different
   * chat than the one it was registered in, the live activeContext on the
   * parent already gives the right chatId for THAT call. Phase 9d.3's
   * design will surface chatId per-handler-invocation, not per-script-run.
   */
  chatIdAtStart?:      string | null;
  characterIdAtStart?: string | null;
  /**
   * Phase 9d.X — snapshots of sync-array-read surfaces at run-dispatch time.
   * Lets the child's proxy implement `api.tools.list()`, `api.macros.list()`,
   * `api.macros.listInterceptors()`, `api.chat.getInjections()`, and
   * `api.chat.listContentProcessors()` synchronously (matching the canonical
   * sync return contract) without an IPC roundtrip per call.
   *
   * The proxy maintains these arrays AS MUTABLE per-run state — register /
   * unregister / inject / removeInjection mutations update the local array
   * eagerly, so user code that does `api.tools.register(...); api.tools.list()`
   * within a single run sees the just-registered tool (matching canonical
   * sync semantics exactly). Cross-script mutations during the same run
   * are NOT reflected (snapshot is dispatch-time + this-script-only diffs);
   * an acceptable best-effort approximation for diagnostic surfaces.
   */
  toolsSnapshot?:                 RegisteredToolInfo[];
  macrosSnapshot?:                RegisteredMacroInfo[];
  macroInterceptorsSnapshot?:     RegisteredMacroInterceptorInfo[];
  chatInjectionsSnapshot?:        InjectionInfo[];
  chatContentProcessorsSnapshot?: RegisteredMessageContentProcessorInfo[];
  /** v0.27.0+ — pre-existing world-info interceptor entries owned by this script. */
  worldInfoInterceptorsSnapshot?: RegisteredWorldInfoInterceptorInfo[];
}

/**
 * Parent's response to an `ApiProxyRequest`. Carries either the resolved
 * value (which may be a `HandleRef` for object-returning methods) or a
 * `SerializedError` if the underlying api call rejected.
 */
export interface ApiProxyResponse {
  type:      'api-response';
  requestId: string;
  ok:        boolean;
  /** Present when `ok === true`. May be a primitive, plain object, or HandleRef. */
  value?:    unknown;
  /** Present when `ok === false`. */
  error?:    SerializedError;
}

/**
 * Parent forwarding a broadcast event firing to the child. The parent owns
 * the bus; child maintains a handler registry keyed by (scriptId, subId).
 * On receipt, the child looks up the closure and invokes it with `payload`.
 */
export interface BroadcastFireMessage {
  type:     'broadcast-fire';
  scriptId: string;
  subId:    string;
  event:    string;
  payload:  unknown;
}

/**
 * Parent telling the child to drop all broadcast subscription handlers
 * owned by `scriptId`. Mirrors the existing `clearBroadcastByScriptId`
 * pattern in the parent's broadcast-bus, applied at the start of every
 * new trigger run for that script. The lifecycle invariant — subscriptions
 * persist BETWEEN runs, wiped at the start of the next run — is preserved.
 */
export interface BroadcastClearMessage {
  type:     'broadcast-clear';
  scriptId: string;
}

/**
 * Graceful-shutdown signal. Parent sends this to ask the child to drain
 * in-flight work and exit cleanly. Used during LumiScript teardown
 * (extension disable / unload). The child responds by calling
 * `process.complete()` when it has nothing else to do; the host then
 * tears down the subprocess.
 *
 * Distinct from a hard kill: hard kills come from the host (SIGKILL on
 * heartbeat timeout) and don't go through this channel.
 */
export interface ShutdownRequest {
  type: 'shutdown';
}

